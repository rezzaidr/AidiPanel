/**
 * AidiPanel — vendor frontend assets into public/assets/ (run via `npm run build`).
 *
 * Copies the third-party assets the panel used to pull from CDNs into the repo so
 * production serves everything from its own origin:
 *   - self-hosted web fonts (Plus Jakarta Sans / Space Grotesk / JetBrains Mono),
 *     latin subset, woff2 only, + a generated public/assets/fonts.css
 *   - Alpine.js and ApexCharts (minified)
 *   - the Tabler icon webfont (default set), with the ttf/svg fallbacks dropped
 *     so only woff2/woff ship (woff2 is what every current browser fetches)
 *
 * Everything written here is a build artifact that is committed and deployed.
 * node_modules is dev-only and never deployed.
 */
import { existsSync, mkdirSync, copyFileSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');               // panel-app/
const NM   = join(ROOT, 'node_modules');
const PUB  = join(ROOT, 'public', 'assets');

const ensure = (d) => mkdirSync(d, { recursive: true });
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
function copy(src, dst) {
  if (!existsSync(src)) throw new Error('missing source asset: ' + src);
  ensure(dirname(dst));
  copyFileSync(src, dst);
  return statSync(dst).size;
}

const log = [];

// ── 1. Body fonts (latin subset, normal style, woff2) ──────────────────────
const FONTS = [
  { family: 'Plus Jakarta Sans', pkg: 'plus-jakarta-sans', weights: [400, 500, 600, 700] },
  { family: 'Space Grotesk',     pkg: 'space-grotesk',     weights: [500, 600, 700] },
  { family: 'JetBrains Mono',    pkg: 'jetbrains-mono',    weights: [500, 600] },
];
const fontsDir = join(PUB, 'fonts');
ensure(fontsDir);
const faces = [];
for (const f of FONTS) {
  for (const w of f.weights) {
    const src  = join(NM, '@fontsource', f.pkg, 'files', `${f.pkg}-latin-${w}-normal.woff2`);
    const name = `${f.pkg}-${w}.woff2`;
    const size = copy(src, join(fontsDir, name));
    log.push(`font   ${name.padEnd(34)} ${kb(size)}`);
    faces.push(
      `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${w};` +
      `font-display:swap;src:url('/assets/fonts/${name}') format('woff2');}`
    );
  }
}
writeFileSync(join(PUB, 'fonts.css'),
`/* AidiPanel — self-hosted web fonts (generated by build/vendor-assets.mjs; do not edit by hand).
   3-font identity: Plus Jakarta Sans = body · Space Grotesk = headings · JetBrains Mono = technical.
   Latin subset, normal style only, font-display: swap. Fallback stacks live in app.css / Tailwind. */
${faces.join('\n')}
`);
log.push(`write   fonts.css (${faces.length} @font-face rules)`);

// ── 2. Vendored runtime JS (Alpine, ApexCharts) ────────────────────────────
const vendor = join(PUB, 'vendor');
ensure(vendor);
log.push(`vendor alpine.min.js      ${kb(copy(join(NM, 'alpinejs', 'dist', 'cdn.min.js'), join(vendor, 'alpine.min.js')))}`);
log.push(`vendor apexcharts.min.js  ${kb(copy(join(NM, 'apexcharts', 'dist', 'apexcharts.min.js'), join(vendor, 'apexcharts.min.js')))}`);

// CodeMirror 5 for the file-manager editor (syntax highlight + line numbers).
// Bundled to ONE js (core + curated modes in dependency order) so the Files tab
// fetches two static assets — no per-mode requests. Lazy-loaded on first edit.
const cmDir   = join(NM, 'codemirror');
const cmModes = ['xml', 'javascript', 'css', 'clike', 'htmlmixed', 'php',
  'markdown', 'yaml', 'shell', 'python', 'sql', 'nginx', 'dockerfile', 'properties'];
let cmBundle = readFileSync(join(cmDir, 'lib', 'codemirror.js'), 'utf8');
for (const m of cmModes) cmBundle += '\n;' + readFileSync(join(cmDir, 'mode', m, m + '.js'), 'utf8');
cmBundle += '\n;' + readFileSync(join(cmDir, 'mode', 'meta.js'), 'utf8');
writeFileSync(join(vendor, 'codemirror.js'), cmBundle);
log.push(`vendor codemirror.js      ${kb(Buffer.byteLength(cmBundle))} (core + ${cmModes.length} modes + meta)`);
const cmCss = readFileSync(join(cmDir, 'lib', 'codemirror.css'), 'utf8') + '\n' + readFileSync(join(cmDir, 'theme', 'dracula.css'), 'utf8');
writeFileSync(join(vendor, 'codemirror.css'), cmCss);
log.push(`vendor codemirror.css     ${kb(Buffer.byteLength(cmCss))} (core + dracula theme)`);

// Icons are no longer a webfont: the panel renders inline local SVGs via the
// icon() helper, synced from @tabler/icons by build/sync-icons.mjs (`npm run icons`).

console.log('Vendored frontend assets:\n' + log.map((l) => '  ' + l).join('\n'));
